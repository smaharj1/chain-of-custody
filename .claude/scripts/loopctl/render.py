"""`render`: BUILD_PLAN.md and the plan diagrams, deterministic and read-only (report section 10.2).

Nothing here writes a file. The Orchestrator redirects stdout (`loopctl render > BUILD_PLAN.md`), which the guards judge as the
ordinary file write it is. Every string from the plan is cleaned (`common.clean_text`, `common.md_cell`): a plan title cannot
carry terminal escapes, table breaks or HTML into the generated view.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from . import common, plan as plan_mod

__all__ = ["render_markdown", "render_mermaid", "render_json"]

_MERMAID_CLASS = {"merged": "done", "abandoned": "dead", "blocked": "stop", "needs_human": "stop", "awaiting_human": "wait",
                  "pr_open": "wait"}


def _status(state: Any, iid: str) -> str:
    if state is None:
        return "pending"
    r = state.items.get(iid)
    return r["status"] if r else "pending"


def render_markdown(lp: Any, state: Any, report: Any, warning: Optional[str] = None, updated: Optional[str] = None) -> str:
    plan = lp.plan or {}
    out = ["<!-- Generated by `loopctl render`. Do not edit: the state is on refs/loopctl/state/%s and the plan in plan/. -->" % common.clean_text(plan.get("name"), 40),
           "# Build Plan: %s" % common.md_cell(plan.get("name") or "(unnamed)", 60), ""]
    if warning:
        out += ["> **%s**" % common.md_cell(warning, 300), ""]
    out += ["**Goal**: %s" % common.clean_text(plan.get("goal"), 1200), ""]
    if updated:
        out += ["**Updated**: %s" % common.clean_text(updated, 40), ""]
    out += ["## Status Board", "", "| ID | Milestone | Title | Depends on | Size | Status |", "|----|-----------|-------|------------|------|--------|"]
    order = report.order or lp.ids()
    for iid in order:
        it = lp.items[iid]
        deps = ", ".join(common.md_cell(d, 24) for d in it.get("dependsOn", []) if isinstance(d, str)) or "-"
        st = _status(state, iid)
        reason = ""
        if state is not None and st in ("blocked", "needs_human"):
            reason = " (%s)" % common.md_cell(state.items[iid].get("blockReason"), 40)
        out.append("| %s | %s | %s | %s | %s | %s%s |" % (common.md_cell(iid, 24), common.md_cell(it.get("milestone"), 60), common.md_cell(it.get("title"), 80),
                                                       deps, common.md_cell(it.get("size"), 2), st, reason))
    counts = state.counts() if state is not None else {}
    done = counts.get("merged", 0)
    out += ["", "Progress: %d/%d merged, %d blocked, %d need a human, %d in progress" % (
        done, len(order), counts.get("blocked", 0), counts.get("needs_human", 0),
        sum(counts.get(s, 0) for s in ("designing", "design_review", "stubbing", "building", "verifying", "reviewing", "pr_open", "awaiting_human")))]
    out += ["", "Critical path: %s (%d items). Widest point of the dependency graph: %d item(s) could run at once." % (
        " -> ".join(report.critical) or "-", len(report.critical), report.width), ""]
    ms = [m for m in (plan.get("milestones") or []) if isinstance(m, str)]
    for m in ms:
        out += ["## %s" % common.md_cell(m, 100), ""]
        for iid in order:
            it = lp.items[iid]
            if it.get("milestone") != m:
                continue
            out.append("### %s: %s" % (common.md_cell(iid, 24), common.md_cell(it.get("title"), 100)))
            out += ["", common.clean_text(it.get("intent"), 800), ""]
            for ac in it.get("acceptance", []):
                if isinstance(ac, dict):
                    out.append("- **%s** %s" % (common.md_cell(ac.get("id"), 30), common.clean_text(ac.get("text"), 600)))
            gate = plan_mod.item_human_gate(it)
            if gate:
                out += ["", "Human gate at merge: %s" % common.md_cell("; ".join(gate), 300)]
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def render_mermaid(lp: Any, state: Any, report: Any) -> str:
    lines = ["flowchart LR"]
    crit = set(report.critical)
    for iid in report.order or lp.ids():
        it = lp.items[iid]
        label = "%s: %s" % (iid, common.clean_text(it.get("title"), 40))
        label = label.replace('"', "'").replace("[", "(").replace("]", ")").replace("<", "(").replace(">", ")")
        lines.append('  %s["%s<br/>%s"]' % (iid, label, _status(state, iid)))
    for iid in report.order or lp.ids():
        for d in lp.items[iid].get("dependsOn", []):
            if isinstance(d, str) and d in lp.items:
                lines.append("  %s %s %s" % (d, "==>" if d in crit and iid in crit else "-->", iid))
    lines += ["  classDef done fill:#d4edda,stroke:#28a745", "  classDef stop fill:#f8d7da,stroke:#dc3545",
              "  classDef wait fill:#fff3cd,stroke:#ffc107", "  classDef dead fill:#e2e3e5,stroke:#6c757d"]
    for iid in report.order or lp.ids():
        cls = _MERMAID_CLASS.get(_status(state, iid))
        if cls:
            lines.append("  class %s %s" % (iid, cls))
    return "\n".join(lines) + "\n"


def render_json(lp: Any, state: Any, report: Any) -> Dict[str, Any]:
    items = []  # type: List[Dict[str, Any]]
    for iid in report.order or lp.ids():
        it = lp.items[iid]
        row = {"id": iid, "title": common.clean_text(it.get("title"), 160), "milestone": it.get("milestone"), "size": it.get("size"),
               "dependsOn": it.get("dependsOn"), "status": _status(state, iid)}
        items.append(row)
    return {"schema": "loopctl.render.v1", "plan": (lp.plan or {}).get("name"), "items": items,
            "critical_path": report.critical, "width": report.width}
