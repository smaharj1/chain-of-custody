"""docs/security/guards.md carries the table of human-only loopctl commands, generated from `kitlib/loopctl_table.py` (review fixes D11 item 8).

    python3 -m tests.guards.test_guards_doc --print      the text to paste between the markers

The test regenerates it and compares, so a change to the table that is not in the doc (or the other way round) fails.
"""
from __future__ import annotations

import os
import sys
import unittest

from kitlib import loopctl_table as t

from tests import REPO_ROOT

DOC = os.path.join(REPO_ROOT, "docs", "security", "guards.md")
BEGIN = "<!-- loopctl-table:begin (generated by `python3 -m tests.guards.test_guards_doc --print`; tests/guards/test_guards_doc.py compares it) -->"
END = "<!-- loopctl-table:end -->"


WHY_OTHER_CHOICE = {"item": "the merge approval and the un-park of a parked item", "unblock": "resets the retry counters"}


def render() -> str:
    human = []   # type: list
    for sub in sorted(t.HUMAN_ONLY):
        human.append(("`loopctl %s %s`" % (sub, ", ".join(sorted(t.HUMAN_ONLY[sub]))), "pushes a ref from this session (D3); only `status`, `list`, `show` as the first word stay reads, so an option before the action is a human step too"))
    for sub in sorted(t.HUMAN_SUB):
        human.append(("`loopctl %s`" % sub, "lifts a stop"))
    for sub in sorted(t.HUMAN_FLAG):
        human.append(("`loopctl %s ... %s`" % (sub, " or ".join(t.HUMAN_FLAG[sub])), "acts on other items or replaces a human-written plan"))
    for sub in sorted(t.HUMAN_UNLESS_DRY_RUN):
        human.append(("`loopctl %s ... %s` (not with `--dry-run`)" % (sub, " or ".join(t.HUMAN_UNLESS_DRY_RUN[sub])), "rolls the integration branch back to a commit"))
    human.append(("`loopctl reconcile ... --live`", "reads GitHub with the human's credential"))
    human.append(("`loopctl reconcile ... --apply` with `%s`" % "` or `".join(t.RECONCILE_FACT_FLAGS), "forces items to merged from a fact file the agent could have written"))
    scopes = sorted(t.APPROVE_RELAY)
    human.append(("`loopctl approve <scope>` for any scope except `%s`" % "`, `".join(scopes),
                  "`plan`, `env`, `breaker`, `cost`, `demotion`: the grant for the whole loop, or a lifted stop"))
    relay = []   # type: list
    for scope in scopes:
        allowed = t.APPROVE_RELAY[scope]
        if allowed is None:
            relay.append(("`loopctl approve %s ...` (any choice)" % scope, "continues inside the approved plan"))
        else:
            relay.append(("`loopctl approve %s ... --choice %s`" % (scope, " or ".join(sorted(allowed))), "narrows or acknowledges"))
            human.append(("`loopctl approve %s ...` with any other choice (the default is `approve`)" % scope, WHY_OTHER_CHOICE.get(scope, "grants")))
    relay.append(("`loopctl reconcile --apply` (no fact file), `loopctl migrate-plan --write` (no `--force`)", "git facts only; creates new files only"))
    lines = [BEGIN, "", "| Human only (denied to every agent, the conductor included: rule `loopctl-human-only`) | Why |", "|---|---|"]
    lines += ["| %s | %s |" % row for row in human]
    lines += ["", "| Relayable (denied to engineers, critics, drivers and unknown callers; the registered conductor may run it after the human said so in the chat: rule `loopctl-write`) | Why |",
              "|---|---|"]
    lines += ["| %s | %s |" % row for row in relay]
    lines += ["", END]
    return "\n".join(lines)


class GuardsDocTable(unittest.TestCase):
    def test_the_table_in_the_doc_is_the_generated_one(self):
        with open(DOC, "r", encoding="utf-8") as fh:
            text = fh.read()
        self.assertIn(BEGIN, text, "docs/security/guards.md has no generated loopctl table")
        got = text[text.index(BEGIN):text.index(END) + len(END)]
        self.assertEqual(got, render(), "regenerate: python3 -m tests.guards.test_guards_doc --print")


if __name__ == "__main__":
    if "--print" in sys.argv:
        print(render())
    else:
        unittest.main()
